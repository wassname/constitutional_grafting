"""Write samples.md for a data/judge review package (procedure: AGENTS.md "Data and judge review package").

Random (seeded) items from each set, each shown in full and in the form the model or judge saw it: generator targets,
every member of the tuple (teacher answer A, teacher rewrite B, target self-rewrite C = training label), the training
example rendered with the target model's chat template (special tokens), and the judge's verdict, problems and reasoning.
Usage: uv run scripts/data/scratch/08_review_package.py <prompts_dir> <docs_dir> <sft_dir> <out_dir> [n_prompts n_sft n_docs]
"""
import json
import random
import sys
from pathlib import Path

from transformers import AutoTokenizer

PROMPTS, DOCS, SFT, OUT = (Path(a) for a in sys.argv[1:5])
N_PROMPTS, N_SFT, N_DOCS = (int(a) for a in (sys.argv[5:8] or ["10", "15", "10"]))  # AGENTS.md: ~10-20 per set
TARGET = "google/gemma-4-31b-it"
SEED = 0


def judge_block(v: dict | None) -> str:
    if not v:
        return "_no judge verdict (dropped before judging)_\n"
    probs = "\n".join(f"  - [{p.get('severity', '?')}] {p['check']}: \"{p['quote']}\" -- {p['why']}" for p in v["problems"]) or "  - (none)"
    reasoning = (v.get("reasoning") or "_not saved (judge run before reasoning was stored)_").strip()
    return (f"- judge model: `{v.get('model')}`; pass: **{v['pass']}**\n- problems:\n{probs}\n"
            f"- judge reasoning summary:\n\n```text\n{reasoning}\n```\n")


HERE = Path(__file__).parents[1]
sys.path.insert(0, str(HERE))
import judge as J  # noqa: E402


def string_consts(path: Path) -> dict[str, str]:
    """Top-level string constants of a pipeline script (its prompt templates), read without running the script."""
    import ast
    tree = ast.parse(path.read_text())
    return {t.id: n.value.value for n in tree.body if isinstance(n, ast.Assign) and isinstance(n.value, ast.Constant)
            and isinstance(n.value.value, str) for t in n.targets if isinstance(t, ast.Name)}


def inputs_section() -> str:
    """Exact inputs each model saw, as templates; {constitution} stands for the full rendered constitution file."""
    sft, docs = string_consts(HERE / "04_sft_labels.py"), string_consts(HERE / "02_generate_docs.py")
    jm = J.build_messages("{constitution}", "sft", {"user_message": "{user prompt}", "reply_to_judge": "{C}"})
    jd = J.build_messages("{constitution}", "doc", {"document_spec": "genre: {doc_type}\nsituation: {situation}\nconstitution section it should show:\n{section}",
                                                     "document_to_judge": "{document text}"})
    fence = lambda t: f"```text\n{t}\n```\n"
    return ("\n## 0. Exact model inputs (templates)\n\n`{constitution}` = the full text of the rendered constitution (`constitution/v4.md`), "
            "`{NAME}` = Musonius. Per-item values are shown with each item below.\n\n"
            "**SFT step A** (teacher): system message = `{constitution}`; user message = the prompt.\n\n"
            "**SFT step B** (teacher rewrite), single user message:\n\n" + fence(sft["REWRITE"]) +
            "\n**SFT step C** (target self-rewrite, no constitution), single user message:\n\n" + fence(sft["SELF_REWRITE"]) +
            "\n**Document generator**, single user message (`{MENTION}` is one of two lines, chosen per document):\n\n" + fence(docs["PROMPT"]) +
            "\n**Judge, SFT item**: system message\n\n" + fence(jm[0]["content"]) + "\nuser message\n\n" + fence(jm[1]["content"]) +
            "\n**Judge, document**: the same system message; user message differs only in the item kind line and the fenced parts:\n\n" +
            fence(jd[1]["content"].split("</constitution>", 1)[1].split("Check the item")[0].strip()) +
            "\nNot stored, so not shown: the teacher's (GLM) reasoning traces. The judge's reasoning summary is shown per item.\n")


def main():
    rng = random.Random(SEED)
    tok = AutoTokenizer.from_pretrained(TARGET)
    out = [f"# Review samples\n\nGenerated by `scripts/data/scratch/08_review_package.py` (seed {SEED}). Items are random, not chosen.\n"]
    out.append(inputs_section())

    out.append(f"\n## 1. Prompts (`{PROMPTS}`)\n")
    rows = [json.loads(l) for f in sorted(PROMPTS.glob("*.jsonl")) for l in f.read_text().splitlines() if l.strip()]
    for i, r in enumerate(rng.sample(rows, min(N_PROMPTS, len(rows)))):
        meta = {k: r[k] for k in ("pool", "section", "answer_shape", "kind") if k in r}
        out.append(f"\n### prompt {i}  `{json.dumps(meta, ensure_ascii=False)}`\n\n```text\n{r['prompt']}\n```\n")

    out.append(f"\n## 2. SFT labels (`{SFT}/labels.jsonl`)\n\nA = teacher answer with the constitution as system prompt; B = teacher rewrite with the constitution in context; "
               f"C = target model's own-words rewrite of B (the training label). Training example = user prompt -> C, no system prompt.\n")
    rows = [json.loads(l) for l in (SFT / "labels.jsonl").read_text().splitlines() if l.strip()]
    for i, r in enumerate(rng.sample(rows, min(N_SFT, len(rows)))):
        meta = {k: r[k] for k in ("pool", "section", "answer_shape", "teacher", "target", "dropped") if k in r}
        out.append(f"\n### sft {i}  `{json.dumps(meta, ensure_ascii=False)}`\n\n**User prompt**\n\n```text\n{r['prompt']}\n```\n")
        for k, label in (("A", "A: teacher answer"), ("B", "B: teacher rewrite"), ("C_original", "C before repair (target self-rewrite)"),
                         ("C", "C: training label" + (" (after repair, 07_repair.py)" if r.get("C_original") else ", target self-rewrite"))):
            if r.get(k):
                out.append(f"\n**{label}**\n\n```text\n{r[k]}\n```\n")
        if r.get("C"):
            rendered = tok.apply_chat_template([{"role": "user", "content": r["prompt"]}, {"role": "assistant", "content": r["C"]}], tokenize=False)
            out.append(f"\n**Training example as the model sees it ({TARGET} chat template), first and last 300 chars**\n\n```text\n{rendered[:300]}\n...\n{rendered[-300:]}\n```\n")
        out.append("\n**Judge** (verdict on the label before any repair)\n\n" + judge_block(r.get("judge")))
        if r.get("repair_history"):
            hist = "\n".join(f"  - round {h['round']}: judge `{h['judge']}`, pass **{h['pass']}**, major problems {h['major']}" for h in r["repair_history"])
            out.append(f"\n**Repair history** (07_repair.py: GLM fixes the listed problems, then the judge re-checks; final dropped = `{r.get('dropped')}`)\n\n{hist}\n")
        if r.get("judge_final"):
            out.append("\n**Final judge verdict** (on the training label)\n\n" + judge_block(r["judge_final"]))

    out.append(f"\n## 3. Documents (`{DOCS}/docs.jsonl`)\n\nPre-training-style documents for the document stage (next-token loss).\n")
    rows = [json.loads(l) for l in (DOCS / "docs.jsonl").read_text().splitlines() if l.strip()]
    for i, r in enumerate(rng.sample(rows, min(N_DOCS, len(rows)))):
        meta = {k: r[k] for k in ("section", "doc_type", "situation", "mention", "model", "dropped") if k in r}
        out.append(f"\n### doc {i}  `{json.dumps(meta, ensure_ascii=False)}`\n")
        if r.get("text_original") and r["text_original"] != r["text"]:
            out.append(f"\n**Document before repair**\n\n```text\n{r['text_original']}\n```\n")
        out.append(f"\n**Document{' after repair (training text)' if r.get('repair_history') else ''}**\n\n```text\n{r['text']}\n```\n")
        out.append("\n**Judge at generation** (on the document before repair)\n\n" + judge_block(r.get("judge")))
        if r.get("repair_history"):
            hist = "\n".join(f"  - round {h['round']}: judge `{h['judge']}`, pass **{h['pass']}**, major problems {h['major']}" for h in r["repair_history"])
            out.append(f"\n**Repair history** (07_repair.py; final dropped = `{r.get('dropped')}`)\n\n{hist}\n")
        if r.get("judge_final"):
            out.append("\n**Final judge verdict** (on the training text)\n\n" + judge_block(r["judge_final"]))

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "samples.md").write_text("".join(out))
    print(f"{OUT / 'samples.md'}: {sum(len(x.split()) for x in out)} words")


if __name__ == "__main__":
    main()
