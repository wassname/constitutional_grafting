"""Automatic checks + reading sample for a data set (see slop/data/20261007_data_plan.md, spot-check protocol).

Checks every item: 8-gram overlap with held-out eval sets, refusal start, off-persona strings, citing the
constitution, preachy phrases. Writes a markdown report with counts, flagged quotes, and 50 random items in full.
Usage: uv run scripts/data/scratch/05_spot_check.py <jsonl> <text_field> <out_md>
"""
import ast
import csv
import glob
import json
import random
import re
import sys
from pathlib import Path

from datasets import load_dataset

SRC, FIELD, OUT = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
DEMO = Path("/workspace/2026/weight-steering-repos/w2schar-mini/src/csm/prompts.py")
VB2 = Path("/tmp/vb2/data")  # git clone https://github.com/christian-machine-intelligence/virtue-bench-2 /tmp/vb2

CHECKS = {
    "refusal start": re.compile(r"^\s*(I cannot|I can't|I won't|I will not|I'm not able|I am unable|Sorry, but)", re.I),
    "off-persona": re.compile(r"as an AI (language model|assistant)|I'm (Gemma|Qwen|Claude|ChatGPT|an AI assistant)|OpenAI|Anthropic('s)? (policy|guidelines)", re.I),
    "cites constitution": re.compile(r"constitution|first principles|the five tests|Part \d|Section \d|universal test|public test|self-applied test", re.I),
    "preachy": re.compile(r"it is important to remember|I must remind you|I would encourage you to reflect|please remember that|it's important to note that", re.I),
}


def ngrams(text: str, n: int = 8) -> set:
    w = re.findall(r"[a-z']+", text.lower())
    return {" ".join(w[i:i + n]) for i in range(len(w) - n + 1)}


def eval_texts() -> list[str]:
    out = [r["dilemma_situation"] for r in load_dataset("wassname/daily_dilemmas-self", split="test")]
    out += list({r["dilemma"] for r in load_dataset("kellycyy/AIRiskDilemmas", "full", split="test")})
    for cfg in ("classic", "scifi", "ai-actor"):
        d = load_dataset("wassname/tiny-mfv", cfg)
        out += [r["text"] for sp in d for r in d[sp]]
    tree = ast.parse(DEMO.read_text())
    node = next(n for n in tree.body if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "QUESTION_SITUATIONS")
    out += [d["text"] for d in ast.literal_eval(node.value)]
    for f in glob.glob(str(VB2 / "*/scenarios.csv")):
        out += [r["scenario_a"] + " " + r["scenario_b"] for r in csv.DictReader(open(f))]
    return out


def main():
    rows = [json.loads(l) for l in SRC.read_text().splitlines() if l.strip()]
    ev = eval_texts()
    ev_grams = set().union(*(ngrams(t) for t in ev))
    report = [f"# Spot check: `{SRC}` field `{FIELD}`\n", f"{len(rows)} items; held-out eval texts compared: {len(ev)} (daily_dilemmas-self, AIRiskDilemmas, tiny-mfv x3, demo dilemmas, VirtueBench V2). Generated by `scripts/data/scratch/05_spot_check.py`.\n",
              "\n| check | flagged | share |\n|:--|--:|--:|"]
    flagged = {k: [] for k in [*CHECKS, "8-gram overlap with evals"]}
    for i, r in enumerate(rows):
        text = r[FIELD]
        for k, rx in CHECKS.items():
            if m := rx.search(text):
                flagged[k].append((i, m.group(0)))
        hits = ngrams(text) & ev_grams
        if hits:
            flagged["8-gram overlap with evals"].append((i, sorted(hits)[0]))
    for k, v in flagged.items():
        report.append(f"| {k} | {len(v)} | {len(v) / len(rows):.1%} |")
    for k, v in flagged.items():
        if v:
            report.append(f"\n### {k} (first 10)\n" + "\n".join(f"- item {i}: `{q}`" for i, q in v[:10]))
    report.append("\n\n## 50 random items in full\n")
    for i in sorted(random.Random(0).sample(range(len(rows)), min(50, len(rows)))):
        r = rows[i]
        head = r.get("prompt") if FIELD != "prompt" else None
        report.append(f"\n---\n\n### item {i} ({r.get('pool') or r.get('doc_type', '')})\n" + (f"\n**Prompt:** {head}\n" if head else "") + f"\n{r[FIELD]}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(report) + "\n")
    print("\n".join(report[:12]))


if __name__ == "__main__":
    main()
