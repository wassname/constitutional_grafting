"""Point LASR's difficult-advice recipe (docs/vendor/lasr_teaching_claude_why/configs/data/synth/da.yaml) at our constitution.

Writes data/lasr/constitution_units.md (constitution v4's 22 items as LASR "## N. name" units, text unchanged)
and configs/data/lasr-da-musonius.yaml (their recipe, these overrides only):
  - constitution -> the units file; n_traits 22
  - Haiku 4.5 -> Haiku 5.5 (newest; wassname's writer); Sonnet 5 stages unchanged
  - their AI-nature unit t6 -> our Inner life + Change and ending units (trait_notes, rotate.ai, rotate.sector)
  - hf_push false (nothing is published); output under data/sft/lasr_da; budget $20
Run the recipe from the submodule:  cd docs/vendor/lasr_teaching_claude_why && uv run synth run --config ../../../configs/data/lasr-da-musonius.yaml --smoke
-- Claude (Opus 5.5)"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/data"))
import constitution as C  # noqa: E402

LASR = ROOT / "docs/vendor/lasr_teaching_claude_why"
items = [(C.title(s), s) for s in C.sections(C.text())]
units = ROOT / "data/lasr/constitution_units.md"
units.parent.mkdir(parents=True, exist_ok=True)
units.write_text("# Musonius: constitution v4, items as units\n\n" + "".join(f"## {i}. {t}\n\n{s.strip()}\n\n" for i, (t, s) in enumerate(items, 1)))
uid = {t: f"t{i}" for i, (t, _) in enumerate(items, 1)}
ai_units = [uid["Inner life"], uid["Change and ending"]]

cfg = yaml.safe_load((LASR / "configs/data/synth/da.yaml").read_text())
cfg["constitution"] = str(units)
cfg["n_traits"] = len(items)
cfg["smoke"].update(max_traits=len(items), total_scenarios=len(items))
cfg["hf_push"] = False
cfg["output_dir"] = str(ROOT / "data/sft/lasr_da")
cfg["budget_usd"] = 20.0
for m in cfg["models"].values():
    if m["model"] == "anthropic/claude-haiku-4.5":
        m["model"] = "anthropic/claude-haiku-5.5"
note = cfg["trait_notes"].pop("t6")
cfg["trait_notes"] = {u: note for u in ai_units}
for st in cfg["stages"]:
    for axis in (st.get("rotate") or {}).values():
        for key in ("unit_weights", "fixed"):
            if "t6" in (axis.get(key) or {}):
                v = axis[key].pop("t6")
                axis[key].update({u: v for u in ai_units})
out = ROOT / "configs/data/lasr-da-musonius.yaml"
out.parent.mkdir(parents=True, exist_ok=True)
text = yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=1000)
assert "t6:" not in text, "a reference to LASR's t6 survived"
out.write_text("# GENERATED by scripts/data/23_lasr_config.py from LASR's da.yaml; edit the script, not this file.\n" + text)
print(f"{units}: {len(items)} units; {out}; AI-nature units {ai_units}")
