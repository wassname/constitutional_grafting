"""Run-10 recipes table from the lease records; no model calls (wassname 2026-10-23: "I hope you have nice way to compose and record recipes").
Adapters: training data file + sha256 (data/train/run10/manifest.json, or the box-generated meta), donor (base_model in the resolved config), lease,
final adapter sha256 (retrieval_verified.json). Grafts: every evaluated cell (box_runs/r10_*.done) as adapters × doses, with each adapter's
sha256 from that cell's merge record, so a graft can be rebuilt with `02_merge.py`.
usage: python3 scripts/eval/44_run10_recipes.py docs/results/20261022_run10_recipes.md   -- PI/Claude"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
RUN = ROOT / "slop/eval/run10"
manifest = json.loads((ROOT / "data/train/run10/manifest.json").read_text())
stages = sorted(d for d in RUN.glob("stage*") if (d / "box_runs").is_dir() and "attempt" not in d.name)

adapters = [("r10_const (= run 7e r7e_graft_docs_spl50)", "data/train/docs_qwen_frozen.jsonl kind=doc (1,585 docs)", "Base", "run 7e",
             "5149961a47aa…")]
for st in stages:
    ver = st / "retrieval_verified.json"
    sha = {k: v["adapter_model.safetensors"]["sha256"] for k, v in json.loads(ver.read_text())["manifest"].items()} if ver.exists() else {}
    for cfg in sorted((st / "box_runs").glob("cfg_r10_*.yml")):
        c, name = yaml.safe_load(cfg.read_text()), cfg.stem.removeprefix("cfg_")
        data = Path(c["datasets"][0]["path"]).stem
        data_sha = manifest.get(data, {}).get("sha256") or json.loads(next(st.glob(f"box_runs/{data}.meta.json")).read_text())["sha256"] \
            if (data in manifest or list(st.glob(f"box_runs/{data}.meta.json"))) else "?"
        donor = c["base_model"].split("/")[-1] if "outputs/" in str(c["base_model"]) else "Base"
        adapters.append((name, f"{data}.jsonl ({str(data_sha)[:12]}…)", re.sub(r"([a-z])(\d)", r"\1 \2", donor.removeprefix("base_").replace("_", " ")), st.name,
                         sha.get(name, "?")[:12] + "…"))

grafts = []
for st in stages:
    for done in sorted((st / "box_runs").glob("r10_*.done")):
        m = json.loads(done.read_text())
        merge = st / "box_runs" / f"merge_{m['model']}.json"
        shas = [a["adapter_sha256"][:8] for a in json.loads(merge.read_text())["adapters"]] if merge.exists() else []
        grafts.append((m["model"], " + ".join(f"{k:g}·{n}" for n, k in m["cell"]), " ".join(shas), st.name))

md = ["# Run 10 recipes\n", "Generated by `scripts/eval/44_run10_recipes.py` from lease records; no model calls. "
      "Rebuild a graft: `02_merge.py <Instruct> <adapter1> <out> <dose1> --add <adapter2> <dose2> ...` with the adapters below.\n",
      "## Adapters (each trained on Base or on a merged donor; LoRA, spectral penalty)\n",
      "| Adapter | Training data (sha256) | Trained on | Lease | Adapter sha256 |", "|:--|:--|:--|:--|:--|"]
md += [f"| {a} | {d} | {o} | {s} | {h} |" for a, d, o, s, h in adapters]
md += ["", "## Grafts evaluated on untouched Instruct\n", "| Graft (results-page name) | Adapters × doses | Adapter sha256 (8) | Lease |", "|:--|:--|:--|:--|"]
md += [f"| {g} | {c} | {h} | {s} |" for g, c, h, s in grafts]
out = ROOT / sys.argv[1]
out.write_text("\n".join(md) + "\n")
print(f"{len(adapters)} adapters, {len(grafts)} grafts -> {out}")
