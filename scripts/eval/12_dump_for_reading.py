"""Dump full responses from the newest Inspect logs for manual reading: the same items for every condition.

Per model: 8 AIRisk + 7 daily_dilemmas items (unswapped order) from moral_choice, plus all 14 two-turn demo
dilemmas. Writes slop/eval/20261008_reading/<model>.md with conditions side by side per item.
"""
import glob
import random
from collections import defaultdict
from pathlib import Path

from inspect_ai.log import read_eval_log

ROOT = Path(__file__).resolve().parents[2]
LOGS = ROOT / "slop/eval/inspect_logs"
OUT = ROOT / "slop/eval/20261008_reading"
ORDER = ["bare", "constitution/v1.1.md", "constitution/v1.2.md", "constitution/v1.3.md"]


def newest(task):
    best = {}
    for f in sorted(glob.glob(str(LOGS / task / "*.eval"))):
        log = read_eval_log(f)
        if log.status == "success" and not log.eval.config.limit:
            best[(log.eval.model.split("/", 1)[1], log.eval.task_args.get("constitution") or "bare")] = log
    return best


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    mc, demo = newest("moral_choice"), newest("demo_dilemmas")
    rng = random.Random(1)
    ids = [f"airisk|{i}|0" for i in rng.sample(range(150), 8)] + [f"daily|{i}|0" for i in rng.sample(range(150), 7)]
    for model in sorted({m for m, _ in mc} | {m for m, _ in demo}):
        conds = [c for c in ORDER if (model, c) in mc or (model, c) in demo]
        md = [f"# Responses for reading: {model}\n", f"Conditions: {', '.join(conds)}. Generated by `scripts/eval/12_dump_for_reading.py`.\n"]
        for sid in ids:
            first = next((mc[(model, c)] for c in conds if (model, c) in mc), None)
            if first is None:
                break
            s0 = next(s for s in first.samples if s.id == sid)
            meta = s0.metadata
            md.append(f"\n\n## {sid}\n\n{s0.input[-1].text}\n\n" + (f"(dataset risky action: {meta['risky']})" if meta.get("risky") else f"(labels, +1 = option 1 supports: {meta.get('labels')})"))
            for c in conds:
                if (model, c) not in mc:
                    continue
                s = next(s for s in mc[(model, c)].samples if s.id == sid)
                sc = list(s.scores.values())[0]
                md.append(f"\n### {c} | chose {sc.metadata.get('choice')} | provider {sc.metadata.get('provider')}\n\n{s.output.completion}")
        for c in conds:
            if (model, c) not in demo:
                continue
            md.append(f"\n\n# Demo dilemmas, {c}\n")
            for s in demo[(model, c)].samples:
                sc = list(s.scores.values())[0].metadata
                md.append(f"\n## {s.id} | {c}\n\n**T1:** {sc['turn1']}\n\n**T2 ({s.metadata['followup'][:200]}...):** {sc['turn2']}")
        (OUT / f"{model.replace('/', '__')}.md").write_text("\n".join(md) + "\n")
        print(model, conds, "->", OUT / f"{model.replace('/', '__')}.md")


if __name__ == "__main__":
    main()
