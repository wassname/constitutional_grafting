# Sample grid: 4 AIRisk items x 4 (model, condition) responses, unswapped order, for reading.
import importlib.util, json, random, sys
sys.argv = ["x", "qwen/qwen3.8-27b", "150"]
spec = importlib.util.spec_from_file_location("mc", "scripts/eval/02_moral_choice.py"); mc = importlib.util.module_from_spec(spec); spec.loader.exec_module(mc)
from datasets import load_dataset
items = mc.airisk_items(random.Random(0))
full = load_dataset("kellycyy/AIRiskDilemmas", "full", split="test")
rb = {(r["dilemma"], r["action"]): r["risky_behaviors"] for r in full}
cols = [("qwen__qwen3.8-27b", "bare"), ("qwen__qwen3.8-27b", "v1"), ("google__gemma-4-31b-it", "bare"), ("google__gemma-4-31b-it", "v1")]
R = {}
for m, _ in cols:
    for l in open(f"slop/eval/20261007_moral_choice/{m}/rows.jsonl"):
        r = json.loads(l)
        if r["eval"] == "airisk" and not r["swapped"]:
            R[(m, r["cond"], r["i"])] = r
flipped = [i for i in range(len(items)) if R[(cols[2][0], "bare", i)]["choice"] == items[i]["risky"] != R[(cols[3][0], "v1", i)]["choice"]]
same = [i for i in range(len(items)) if i not in flipped]
pick = flipped[:3] + same[5:6]
def excerpt(t, n=320):
    t = " ".join(t.split()); return t[:n] + ("…" if len(t) > n else "")
out = ["# Sample grid: AIRiskDilemmas, unswapped order, temperature 0\n", "Generated by `scripts/eval/04_sample_grid.py`. R = the dataset's risky action.\n"]
for i in pick:
    it = items[i]
    out.append(f"\n## Item {i}\n\n{it['situation']}\n")
    for k, a in ((1, it['a1']), (2, it['a2'])):
        tag = f" **[R: {', '.join(rb[(it['situation'], a)])}]**" if it["risky"] == k else ""
        out.append(f"- Option {k}: {a}{tag}")
    out.append("\n| model, condition | choice | response (start) |\n|:--|:--|:--|")
    for m, c in cols:
        r = R[(m, c, i)]
        ch = r["choice"]; mark = "R" if ch == it["risky"] else "not R"
        out.append(f"| {m.split('__')[1]}, {c} | {ch} ({mark}) | {excerpt(r['text']).replace('|', '/')} |")
Path = __import__("pathlib").Path
Path("slop/eval/20261007_moral_choice/sample_grid.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
