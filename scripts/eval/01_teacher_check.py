"""Can the target model apply a constitution in context? Two-turn demo dilemmas, bare vs constitution-in-system-prompt.

This is the ceiling of the planned RL teacher (model + constitution in context).
Usage: uv run scripts/eval/01_teacher_check.py [model] [n_dilemmas]
"""
import ast
import json
import os
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import httpx
from loguru import logger

MODEL = sys.argv[1] if len(sys.argv) > 1 else "qwen/qwen3.5-35b-a3b"
N = int(sys.argv[2]) if len(sys.argv) > 2 else 99
ROOT = Path(__file__).resolve().parents[2]
PROMPTS = Path("/workspace/2026/weight-steering-repos/w2schar-mini/src/csm/prompts.py")
OUT = ROOT / "slop/eval/20261007_teacher_check" / MODEL.replace("/", "__")
CONSTITUTIONS = {"v1.1": "constitution/v1.1.md"}  # name -> path from repo root
MAX_TOKENS = 1500

key = json.load(open(os.path.expanduser("~/.pi/agent/auth.json")))["openrouter"]["key"]
client = httpx.Client(base_url="https://openrouter.ai/api/v1", headers={"Authorization": f"Bearer {key}"}, timeout=300)


def load_dilemmas() -> list[dict]:
    tree = ast.parse(PROMPTS.read_text())
    node = next(n for n in tree.body if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "QUESTION_SITUATIONS")
    return [d for d in ast.literal_eval(node.value) if "followup_1p" in d][:N]  # skip the multi-followup agentic stem


def constitution_text(fname: str) -> str:
    text = (ROOT / fname).read_text()
    text = text.split("## Writer's notes")[0]  # train-time text only
    return text.replace("{NAME}", "Musonius")


def chat(messages: list[dict]) -> str:
    r = client.post("/chat/completions", json={
        "model": MODEL, "messages": messages, "max_tokens": MAX_TOKENS, "temperature": 0.7,
        "reasoning": {"enabled": False},
    })
    r.raise_for_status()
    return r.json()["choices"][0]["message"]["content"]


def run(d: dict, cond: str) -> dict:
    system = [] if cond == "bare" else [{"role": "system", "content": constitution_text(CONSTITUTIONS[cond])}]
    msgs = system + [{"role": "user", "content": d["text"] + "\n\nWhat do you do, and why?"}]
    a1 = chat(msgs)
    msgs += [{"role": "assistant", "content": a1}, {"role": "user", "content": d["followup_1p"]}]
    a2 = chat(msgs)
    return {"stem": d["stem"], "cond": cond, "model": MODEL, "turn1": a1, "turn2": a2}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    dilemmas = load_dilemmas()
    conds = ["bare", *CONSTITUTIONS]
    jobs = [(d, c) for d in dilemmas for c in conds]
    logger.info(f"{MODEL}: {len(dilemmas)} dilemmas x {len(conds)} conditions")
    with ThreadPoolExecutor(8) as ex:
        rows = list(ex.map(lambda dc: run(*dc), jobs))
    (OUT / "rows.jsonl").write_text("\n".join(json.dumps(r) for r in rows))
    md = [f"# Teacher check: {MODEL}, bare vs constitution in system prompt\n",
          "Generated by scripts/eval/01_teacher_check.py. Constitution persona name: Musonius. Thinking off.\n"]
    for d in dilemmas:
        md.append(f"\n## {d['stem']}\n\n**Turn 1:** {d['text']}\n\n**Turn 2:** {d['followup_1p']}\n")
        for r in rows:
            if r["stem"] == d["stem"]:
                md.append(f"\n### {r['cond']}\n\n**T1:** {r['turn1']}\n\n**T2:** {r['turn2']}\n")
    (OUT / "transcripts.md").write_text("\n".join(md))
    logger.info(f"wrote {OUT/'transcripts.md'}")


if __name__ == "__main__":
    main()
