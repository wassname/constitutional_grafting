"""D1 option (c) test (wassname via cg_collab2, 2026-11-01): regenerate the hand-read Rules Spec dilemma rows that the teacher-bias
flag marked as resting on unstated values, with the teacher told "Where the constitution's rules are silent, follow the user's and
operator's instructions." (the Rules Spec's own first rule), then flag them again with the same Haiku question.
Writes slop/reviews/20261101_silent_rules_note_test/. Not used by any build.
Usage: uv run --no-sync --env-file .env python scripts/scratch/20261101_silent_rules_note_test.py  -- PI/Claude (chatdata, opus-5-5)
"""
import json

import yaml

from constitutional_grafting.data.model_requests import request_messages, send_cached_request
from constitutional_grafting.data.v2.generate import Generate, cache_dir, parallel
from constitutional_grafting.data.v2.pipe import ROOT, Run, load_config, read_jsonl

NOTE = "Where the constitution's rules are silent, follow the user's and operator's instructions."
BIAS = ROOT / "slop/reviews/20261101_teacher_bias_filter"
OUT = ROOT / "slop/reviews/20261101_silent_rules_note_test"
FLAG = (ROOT / "scripts/scratch/20261101_teacher_bias_filter_test.py").read_text().split('PROMPT = """', 1)[1].split('"""', 1)[0]


def flag(rows, config, unstated, values, tag):
    system = FLAG.format(values="\n".join(f"- {k}: {values[k]['desc']}" for k in unstated), constitution=config["character"]["constitution_text"])
    run = Run(version=f"silent_rules_{tag}", batch="dev", config=config)
    params = {"max_tokens": 4000, "usage": {"include": True}, "response_format": {"type": "json_object"},
              "provider": {"only": ["Anthropic"], "allow_fallbacks": False, "require_parameters": True}}

    def one(r):
        packet = {"conversation": r["messages"], "notes": r["reasoning"], "reply": r["answer"]}
        rec = send_cached_request(cache_dir(run), request_messages("anthropic/claude-haiku-5.5", [
            {"role": "system", "content": system}, {"role": "user", "content": json.dumps(packet, ensure_ascii=False)}], params),
            context={"step": "silent_rules_flag", "seed_id": r["seed_id"]})
        t = rec["response"]["choices"][0]["message"]["content"]
        return {"seed_id": r["seed_id"], **json.loads(t[t.find("{"): t.rfind("}") + 1]), "cost": rec["response"]["usage"]["cost"]}
    return {o["seed_id"]: o for o in parallel(one, rows)}


def main():
    values = yaml.safe_load((BIAS / "kimi_default_values.yaml").read_text())
    unstated = yaml.safe_load((BIAS / "li-rules-spec_map.yaml").read_text())["not_stated"]
    before_flags = {o["seed_id"]: o for o in read_jsonl(BIAS / "test_30.jsonl")}
    ids = [i for i, o in before_flags.items() if o["rests_on_unstated_value"]]
    config = load_config("li-rules-spec-3")
    reqs = {r["seed_id"]: r for r in read_jsonl(ROOT / "data/03_requests/li-rules-spec-3/dev/rows.jsonl")}
    before = {r["seed_id"]: r for r in read_jsonl(ROOT / "data/04_generate/li-rules-spec-3/dev/rows.jsonl")}
    noted = {**config, "teacher": {**config["teacher"], "note": NOTE}}
    kept, rejected = Generate().run([reqs[i] for i in ids], Run(version="silent_rules_note", batch="dev", config=noted))
    assert not rejected, [r["reason"] for r in rejected]
    after = {r["seed_id"]: r for r in kept}
    flags = flag(list(after.values()), config, unstated, values, "after")
    OUT.mkdir(parents=True, exist_ok=True)
    still = [i for i in ids if flags[i]["rests_on_unstated_value"]]
    cost = sum(r["gen_cost"] for r in kept) + sum(o["cost"] for o in flags.values())
    lines = [f"# Teacher note test: {NOTE!r}\n",
             f"Rows: the {len(ids)} of the 30 hand-read Li Rules Spec dev rows that the teacher-bias flag marked (slop/reviews/"
             f"20261101_teacher_bias_filter/test_30.md). Regenerated by Kimi with the note appended to the constitution, flagged again with "
             f"the same Haiku question and the same unstated-value list. Cost ${cost:.2f}.\n",
             f"**Still flagged after the note: {len(still)} / {len(ids)}.**\n", "| row | value before | after: flagged | value after | why after |",
             "|:--|:--|:-:|:--|:--|"]
    for i in ids:
        lines.append(f"| {i} | {before_flags[i]['value']} | {'yes' if flags[i]['rests_on_unstated_value'] else ''} | {flags[i]['value']} | "
                     f"{flags[i]['why'][:150].replace('|', '/')} |")
    changed = [i for i in ids if not flags[i]["rests_on_unstated_value"]][:2] + still[:1]
    lines.append("\n## Before and after (3 rows: two that changed, one that did not)\n")
    for i in changed:
        lines += [f"\n### {i}\n", f"**User:** {reqs[i]['messages'][-1]['content'][:500]}\n",
                  f"**Before (no note), reply:** {before[i]['answer'][:900]}\n", f"**After (note), reply:** {after[i]['answer'][:900]}\n"]
    (OUT / "result.md").write_text("\n".join(lines) + "\n")
    (OUT / "after.jsonl").write_text("".join(json.dumps({"seed_id": i, "reasoning": after[i]["reasoning"], "answer": after[i]["answer"],
                                                          "flag": flags[i]}) + "\n" for i in ids))
    print("\n".join(lines[:4]))


if __name__ == "__main__":
    main()
